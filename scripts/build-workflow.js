#!/usr/bin/env node
'use strict';

/**
 * scripts/build-workflow.js
 * ---------------------------------------------------------------------------
 * Compiles error-parser.js into the n8n Code nodes of workflow.json, so the
 * JavaScript that runs in n8n is exactly the JavaScript the tests cover.
 *
 *   node scripts/build-workflow.js           write workflow.json
 *   node scripts/build-workflow.js --check   exit 1 if workflow.json is stale (CI)
 *
 * Credentials are placeholders (REPLACE_WITH_... IDs). Webhook URLs and the
 * Datadog site are read from environment variables at runtime.
 *
 * DISCLAIMER: provided "AS IS", without warranty of any kind. See DISCLAIMER.md.
 * ---------------------------------------------------------------------------
 */

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const ROOT = path.resolve(__dirname, '..');
const OUTPUT = path.join(ROOT, 'workflow.json');
const PKG = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
const HUBSPOT_API = 'https://api.hubapi.com';

const CREDENTIALS = Object.freeze({
  hubspot: { hubspotAppToken: { id: 'REPLACE_WITH_HUBSPOT_CREDENTIAL_ID', name: 'HubSpot Private App (REPLACE_WITH_HUBSPOT_PAT)' } },
  datadog: { httpHeaderAuth: { id: 'REPLACE_WITH_DATADOG_CREDENTIAL_ID', name: 'Datadog DD-API-KEY (REPLACE_WITH_DATADOG_API_KEY)' } },
});
const RETRY = Object.freeze({ retryOnFail: true, maxTries: 3, waitBetweenTries: 2000 });

function stableId(seed) {
  const h = crypto.createHash('sha1').update(`cca-error-handler:${seed}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

function readParser() {
  const source = fs.readFileSync(path.join(ROOT, 'error-parser.js'), 'utf8');
  if (source.split('\n').filter((l) => !/^\s*(\*|\/\/|\/\*)/.test(l)).some((l) => /\brequire\s*\(/.test(l))) {
    throw new Error('error-parser.js must not call require(); it is inlined into n8n Code nodes.');
  }
  return source.trimEnd();
}

function preamble() {
  return [
    `// ===== AUTO-GENERATED by scripts/build-workflow.js (v${PKG.version}). Do not edit in n8n. =====`,
    '// Source: error-parser.js. Edit it, run `npm run build`, then re-import workflow.json.',
    '// DISCLAIMER: provided "AS IS" without warranty. See DISCLAIMER.md.',
    'const Parser = (function () { const module = { exports: {} }; const exports = module.exports;',
    readParser(),
    'return module.exports; })();',
    '/** Copy only known keys from $env; tolerates N8N_BLOCK_ENV_ACCESS_IN_NODE=true. */',
    'function __readEnv() {',
    '  const env = {};',
    '  let source;',
    '  try { source = $env; } catch (err) { source = undefined; }',
    '  if (!source) return env;',
    '  for (const key of Parser.ENV_KEYS) {',
    "    try { const v = source[key]; if (v !== undefined && v !== null && v !== '') env[key] = String(v); } catch (err) { /* blocked */ }",
    '  }',
    '  return env;',
    '}',
    'function __runId() { try { return $execution && $execution.id ? String($execution.id) : null; } catch (err) { return null; } }',
    '',
  ].join('\n');
}

const ENTRIES = {
  parse: `// ===== ENTRY: Normalize & Parse Errors =====
// Fail fast on bad configuration; bad or unauthenticated payloads are dropped and counted, never thrown.
const config = Parser.loadConfig(__readEnv());
let store = null;
try { store = $getWorkflowStaticData('global'); } catch (err) { store = null; } // alert de-duplication state
try {
  const result = Parser.processWebhookItems($input.all(), config, new Date(), { store, runId: __runId() });
  if (Object.keys(result.rejected).length) console.log('[cca-errors] rejected ' + JSON.stringify(result.rejected));
  result.events.forEach((e) => (e.log.intakeUrl = config.datadog.intakeUrl));
  return result.events.map((json) => ({ json }));
} catch (err) {
  console.log('[cca-errors] parser failure: ' + Parser.redact(err && err.message ? err.message : String(err)));
  return []; // explicit fallback: never fail the webhook execution on a malformed report
}
`,
  dryRun: `// ===== ENTRY: Dry-Run Telemetry =====
// SANDBOX_MODE=true: log what would be alerted, logged and retried; nothing is sent.
try {
  const report = Parser.buildDryRunReport($input.all().map((i) => i.json));
  report.lines.forEach((l) => console.log(l));
  return [{ json: report }];
} catch (err) {
  return [{ json: { kind: 'dry_run_report', status: 'REPORT_ERROR', error: Parser.redact(err && err.message ? err.message : String(err)) } }];
}
`,
  console: `// ===== ENTRY: Console Logger =====
// Used when ENABLE_DATADOG=false: one JSON line per event on the n8n process stdout.
return $input.all().map((item) => {
  const line = item.json && item.json.log ? item.json.log.line : '';
  if (line) console.log(line);
  return { json: { logged: Boolean(line), fingerprint: item.json ? item.json.fingerprint : null } };
});
`,
};

function codeNode(name, entry, position, notes) {
  return { parameters: { jsCode: `${preamble()}\n${ENTRIES[entry]}` }, id: stableId(name), name, type: 'n8n-nodes-base.code', typeVersion: 2, position, notes };
}

function http(name, position, parameters, extra) {
  return Object.assign({ parameters, id: stableId(name), name, type: 'n8n-nodes-base.httpRequest', typeVersion: 4.2, position }, RETRY, { onError: 'continueRegularOutput' }, extra || {});
}

function condition(id, leftValue, operator, rightValue) {
  return { id: stableId(id), leftValue, rightValue: rightValue === undefined ? '' : rightValue, operator };
}

const isTrue = { type: 'boolean', operation: 'true', singleValue: true };
const strEq = { type: 'string', operation: 'equals' };

function ifNode(name, conds, position) {
  return {
    parameters: { conditions: { options: { caseSensitive: true, leftValue: '', typeValidation: 'loose' }, conditions: conds, combinator: 'and' }, options: {} },
    id: stableId(name),
    name,
    type: 'n8n-nodes-base.if',
    typeVersion: 2,
    position,
  };
}

function switchRule(label, conds) {
  return { conditions: { options: { caseSensitive: true, leftValue: '', typeValidation: 'loose' }, conditions: conds, combinator: 'and' }, renameOutput: true, outputKey: label };
}

function switchNode(name, rules, position, notes) {
  return { parameters: { rules: { values: rules }, options: {} }, id: stableId(name), name, type: 'n8n-nodes-base.switch', typeVersion: 3, position, notes };
}

const hubspotAuth = { authentication: 'predefinedCredentialType', nodeCredentialType: 'hubspotAppToken' };
const jsonBody = (expr) => ({ sendBody: true, specifyBody: 'json', jsonBody: expr });

function buildWorkflow() {
  const nodes = [
    {
      parameters: {
        content:
          '## HubSpot Custom Code Action Error Handler\n' +
          'HubSpot custom code actions report failures here (see hubspot/custom-code-wrapper.js). Errors are parsed, classified, ' +
          'alerted to Slack, logged to Datadog or the console, and recovered by retry (record flag + re-enrolment) or fallback (flag + task).\n\n' +
          '**Safe by default:** `SANDBOX_MODE=true` routes everything to *Dry-Run Telemetry*.\n\n' +
          'Code nodes are generated from `error-parser.js` by `npm run build`; do not edit them in n8n.',
        height: 300,
        width: 560,
        color: 2,
      },
      id: stableId('Overview'),
      name: 'Overview',
      type: 'n8n-nodes-base.stickyNote',
      typeVersion: 1,
      position: [-140, -380],
    },
    {
      parameters: { httpMethod: 'POST', path: 'hubspot/custom-code-errors', responseMode: 'onReceived', options: {} },
      id: stableId('HubSpot Error Webhook'),
      name: 'HubSpot Error Webhook',
      type: 'n8n-nodes-base.webhook',
      typeVersion: 2,
      position: [0, 100],
      webhookId: stableId('hubspot-error-webhook'),
      notes: 'Responds immediately (200) so the HubSpot action is not slowed down. Authenticated by the x-hs-error-secret header in the next node.',
    },
    codeNode('Normalize & Parse Errors', 'parse', [240, 100], 'Authenticates, parses stack traces and API errors, classifies, de-duplicates alerts and plans recovery.'),
    ifNode('Sandbox Mode?', [condition('sandbox', '={{ $json.sandbox }}', isTrue)], [480, 100]),
    codeNode('Dry-Run Telemetry', 'dryRun', [720, -120], 'Sandbox branch: logs planned alerts, logs and recovery actions.'),

    // Slack alert router
    switchNode(
      'Slack Alert Router',
      [
        switchRule('Critical Channel', [condition('slack-crit-send', '={{ $json.alert.send }}', isTrue), condition('slack-crit-route', '={{ $json.alert.route }}', strEq, 'critical')]),
        switchRule('Default Channel', [condition('slack-def-send', '={{ $json.alert.send }}', isTrue), condition('slack-def-route', '={{ $json.alert.route }}', strEq, 'default')]),
      ],
      [720, 80],
      'Events below ALERT_MIN_SEVERITY or de-duplicated within ALERT_DEDUPE_MINUTES match no rule and are not posted.'
    ),
    http('Slack Critical Alert', [960, 0], Object.assign({ method: 'POST', url: '={{ $env.SLACK_CRITICAL_WEBHOOK_URL }}', options: { timeout: 10000 } }, jsonBody('={{ JSON.stringify($json.alert.payload) }}')), {
      notes: 'Incoming Webhook from SLACK_CRITICAL_WEBHOOK_URL (critical errors such as AUTH and CODE).',
    }),
    http('Slack Alert', [960, 140], Object.assign({ method: 'POST', url: '={{ $env.SLACK_WEBHOOK_URL }}', options: { timeout: 10000 } }, jsonBody('={{ JSON.stringify($json.alert.payload) }}')), {
      notes: 'Incoming Webhook from SLACK_WEBHOOK_URL.',
    }),

    // Datadog / console logger
    ifNode('Datadog Enabled?', [condition('dd-enabled', '={{ $json.log.datadogEnabled }}', isTrue)], [720, 300]),
    http(
      'Datadog Log Intake',
      [960, 260],
      Object.assign(
        { method: 'POST', url: '={{ $json.log.intakeUrl }}', authentication: 'genericCredentialType', genericAuthType: 'httpHeaderAuth', options: { timeout: 10000 } },
        jsonBody('={{ JSON.stringify($json.log.datadog) }}')
      ),
      { credentials: CREDENTIALS.datadog, notes: 'POST https://http-intake.logs.<DATADOG_SITE>/api/v2/logs with header DD-API-KEY.' }
    ),
    codeNode('Console Logger', 'console', [960, 400], 'Structured JSON line per event on stdout (when Datadog is disabled).'),

    // Retry / fallback router
    switchNode(
      'Retry / Fallback Router',
      [
        switchRule('Retry', [condition('rec-retry', '={{ $json.recovery.action }}', strEq, 'RETRY')]),
        switchRule('Fallback', [condition('rec-fallback', '={{ $json.recovery.action }}', strEq, 'FALLBACK')]),
      ],
      [720, 560],
      'NONE (no record reference, or recovery disabled) matches no rule.'
    ),
    {
      parameters: { resume: 'timeInterval', amount: '={{ $json.recovery.delaySeconds }}', unit: 'seconds' },
      id: stableId('Retry Backoff'),
      name: 'Retry Backoff',
      type: 'n8n-nodes-base.wait',
      typeVersion: 1.1,
      position: [960, 520],
      webhookId: stableId('retry-backoff'),
      notes: 'Exponential backoff with jitter (RETRY_BASE_DELAY_SECONDS × 2^attempt, capped at RETRY_MAX_DELAY_SECONDS).',
    },
    http(
      'HubSpot Request Retry',
      [1200, 520],
      Object.assign({ method: 'PATCH', url: `=${HUBSPOT_API}{{ $json.recovery.updatePath }}`, options: { timeout: 15000 } }, hubspotAuth, jsonBody('={{ JSON.stringify({ properties: $json.recovery.properties }) }}')),
      { credentials: CREDENTIALS.hubspot, notes: 'Sets cca_error_status=RETRY_REQUESTED and increments cca_retry_count; the HubSpot workflow re-enrols on that change.' }
    ),
    http(
      'HubSpot Flag Fallback',
      [960, 680],
      Object.assign({ method: 'PATCH', url: `=${HUBSPOT_API}{{ $json.recovery.updatePath }}`, options: { timeout: 15000 } }, hubspotAuth, jsonBody('={{ JSON.stringify({ properties: $json.recovery.properties }) }}')),
      { credentials: CREDENTIALS.hubspot, notes: 'Sets cca_error_status=FALLBACK plus last-error details for a fallback branch or view.' }
    ),
    ifNode('Fallback Task Needed?', [condition('task-needed', '={{ !!$json.recovery.task }}', isTrue)], [960, 840]),
    http(
      'HubSpot Create Fallback Task',
      [1200, 840],
      Object.assign({ method: 'POST', url: `${HUBSPOT_API}/crm/v3/objects/tasks`, options: { timeout: 15000 } }, hubspotAuth, jsonBody('={{ JSON.stringify($json.recovery.task) }}')),
      { credentials: CREDENTIALS.hubspot, notes: 'Task for RevOps / the fallback owner, associated with the failed record.' }
    ),
  ];

  const link = (node) => ({ node, type: 'main', index: 0 });
  const connections = {
    'HubSpot Error Webhook': { main: [[link('Normalize & Parse Errors')]] },
    'Normalize & Parse Errors': { main: [[link('Sandbox Mode?')]] },
    'Sandbox Mode?': { main: [[link('Dry-Run Telemetry')], [link('Slack Alert Router'), link('Datadog Enabled?'), link('Retry / Fallback Router')]] },
    'Slack Alert Router': { main: [[link('Slack Critical Alert')], [link('Slack Alert')]] },
    'Datadog Enabled?': { main: [[link('Datadog Log Intake')], [link('Console Logger')]] },
    'Retry / Fallback Router': { main: [[link('Retry Backoff')], [link('HubSpot Flag Fallback'), link('Fallback Task Needed?')]] },
    'Retry Backoff': { main: [[link('HubSpot Request Retry')]] },
    'Fallback Task Needed?': { main: [[link('HubSpot Create Fallback Task')], []] },
  };

  return {
    name: 'HubSpot Custom Code Action Error Handler',
    nodes,
    pinData: {},
    connections,
    active: false,
    settings: { executionOrder: 'v1', saveManualExecutions: true, callerPolicy: 'workflowsFromSameOwner' },
    meta: { templateCredsSetupCompleted: false, generatedBy: `${PKG.name}@${PKG.version}` },
    tags: [],
  };
}

function serialize(workflow) {
  return `${JSON.stringify(workflow, null, 2)}\n`;
}

function main(argv) {
  const output = serialize(buildWorkflow());
  if (argv.includes('--check')) {
    const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
    if (current !== output) {
      console.error('workflow.json is out of date with error-parser.js. Run `npm run build` and commit the result.');
      return 1;
    }
    console.log('workflow.json is up to date.');
    return 0;
  }
  fs.writeFileSync(OUTPUT, output);
  console.log(`Wrote workflow.json (${Buffer.byteLength(output)} bytes, ${buildWorkflow().nodes.length} nodes).`);
  return 0;
}

if (require.main === module) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (err) {
    console.error(`Build failed: ${err.message}`);
    process.exitCode = 1;
  }
}

module.exports = { buildWorkflow, serialize, stableId, CREDENTIALS };
